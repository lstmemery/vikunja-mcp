# Пуш в main и тег — ОДИН АТОМАРНЫЙ push и точка линеаризации: выиграть его может ровно
# один job на вершину, а канал пушится только после победы. Остаточное окно между
# проверкой выше и этим push'ем закрывается ПЕРЕПРОВЕРКОЙ, а не молчаливым ретраем.
#
# ПОЧЕМУ ДВА РЕФА В ОДНОМ PUSH'Е (tracker #723). Раздельными push'ами шаг оставлял
# ПОЛУ-СОСТОЯНИЕ: bump уезжал в main, а отказ на push'е ТЕГА (сеть, 5xx, защита рефов)
# оставлял версию без тега. Само оно не лечится и перезапуском тоже: следующее приземление
# бампит СЛЕДУЮЩИЙ патч, поэтому пропущенная версия не появляется НИКОГДА и откатиться на
# неё (`git branch -f stable vX.Y.Z`) больше нечем. Измерено на стенде хуком, отвергающим
# только `refs/tags/*`: `tags = []` при `__version__ = "0.2.171"` на вершине main, exit 1;
# перезапуск ТОГО ЖЕ job'а отвечал ЗЕЛЁНЫМ `release skipped` (предтеговой гейт читает
# собственный осиротевший bump как «меня накрыли»), а следующее приземление выпускало
# v0.2.172. С атомарным push'ем тот же вход не оставляет НИЧЕГО: main остаётся на своём
# sha, версия на его вершине прежняя, тега нет, job красный — то есть «bump без тега» этот
# шаг больше не СТРОИТ, а не строит громче. Громким-то он был и раньше (`set -eu`), и
# ровно поэтому одной диагностики было мало: чинить нечего, если версия уже пропущена.
#
# ЗАЩИТА ДВУСОСТАВНАЯ, и какая половина работает — зависит ОТ ФОРМЫ ОТКАЗА СЕРВЕРА, а не от
# вкуса. Замерено на двух видах хуков, потому что разница ровно тут:
#   `pre-receive` — ОДИН на push, поэтому, выйдя ненулём, отвергает ВСЮ пачку и БЕЗ всякого
#   флага (проверено: тот же вход на неатомарной пачке тоже не оставляет ничего). На таком
#   отказе достаточно уже того, что рефспека два в одной команде.
#   `update` — ПО РЕФУ, и это форма, в которой отказывает ref-protection хостинга. Тут
#   неатомарная пачка берёт что может, и оба направления измерены. Отвергнут ТЕГ: `HEAD ->
#   main` уезжает, `! [remote rejected] v1 -> v1 (hook declined)` — то есть ровно то
#   «bump без тега», ради которого заведена #723, строится и ОДНОЙ командой; с флагом тот же
#   вход даёт `! [remote rejected] HEAD -> main (atomic push failure)` и нетронутый main.
#   И этот вход без флага чуть не оказался ТИШЕ прежнего, а не просто «таким же»: прогнанный
#   целиком, он давал клиенту отказ, перепроверка задавала ПЕРВЫЙ вопрос, видела свой bump на
#   main, печатала «finishing the release», двигала канал — rc 0, релиз БЕЗ ТЕГА и без единого
#   сигнала, тогда как до #723 отдельный push тега тут краснел под `set -eu`. Именно этот
#   прогон и завёл проверку тега в той ветке (см. ниже); теперь тот же вход краснеет с «the
#   push was accepted NON-atomically». Слоя, стало быть, ДВА и они про разное: `--atomic` не
#   даёт состоянию ВОЗНИКНУТЬ, проверка тега не даёт ему пройти ТИХО. Пин на второй —
#   test_without_atomic_the_refused_tag_bumps_main_anyway (на remote там полу-состояние ЕСТЬ,
#   просто замечено), пин на первый — test_a_refused_tag_leaves_nothing_behind.
#   Отвергнут MAIN (не-ff при свободном имени тега): неатомарный push создаёт
#   `* [new tag] v0.2.171` рядом с `! [rejected] HEAD -> main`, то есть ТЕГ-СИРОТУ на
#   коммите, которого в main нет. Второе — не «другая половина той же дыры», а состояние
#   ХУЖЕ: следующее приземление его не лечит, а упирается в него (версия на вершине main
#   осталась прежней, значит считается ТА ЖЕ) и умирает на `fatal: tag 'vX.Y.Z' already
#   exists` — прогнано два приземления подряд, оба rc 128 (в пине живёт одно), и дальше то же
#   по механике. Причём job, который сироту завёл, ЗЕЛЁНЫЙ: перепроверка честно видит «меня
#   накрыли». Так что «просто сложить два рефспека в одну строку» — не дешёвая замена, а
#   регрессия; и «bump без тега строится только раздельными push'ами» было бы ЛОЖЬЮ — оно
#   верно ровно для отказа-целиком. Обе половины запинены мутационно, каждая своей мутацией
#   и своим хуком (`_release_sh_with_a_separate_tag_push` на `pre-receive`,
#   `_release_sh_without_atomic` на `update`).
#
# ЦЕНА АТОМАРНОСТИ, КОТОРУЮ НАДО НАЗВАТЬ: она убрала не только полу-состояние, но и один
# СЛУЧАЙНЫЙ ВЫХОД. Если имя версии занято на remote ЧУЖИМ тегом, появившимся ПОСЛЕ чекаута
# job'а (в чекауте его нет, поэтому локальный `git tag -a` проходит и всё решает push),
# раздельные push'и вели себя так: main уезжал, версия на вершине двигалась мимо
# сквоттера, и следующее же приземление считало СЛЕДУЮЩИЙ патч — один красный job, дальше
# само. Измерено на стенде, до-#723 код: первый job rc 1, затем три приземления подряд rc 0,
# версия дошла до 0.2.174, теги v0.2.171..174, канал на месте. С атомарным push'ем не
# уезжает НИЧЕГО, поэтому версия на вершине остаётся прежней, каждый следующий job считает
# ТУ ЖЕ занятую версию и умирает на `git tag -a`: те же три приземления дают rc 128, 128,
# 128, версия стоит на 0.2.170, канал не двигается ВООБЩЕ. Инвариант при этом цел — каждый
# прогон КРАСНЫЙ, тихого зелёного тут нет ни одного, — но «один красный и само зарастёт»
# стало «канал стоит, пока человек не удалит чужой тег». Разменяно сознательно: полу-состояние
# было ТИХИМ и невосстановимым (пропущенная версия не появится никогда), а это — громкое и
# лечится одной командой человека (`git push origin :refs/tags/vX.Y.Z`). Класс «сквоттер
# имени версии» отдан отдельной карточкой — #769.
#
# АТОМАРНОСТЬ — СВОЙСТВО СЕРВЕРА, и это ЗАВИСИМОСТЬ, которую надо знать, а не деталь
# флага. Клиент требует, чтобы receive-pack advertise'ил возможность `atomic`; не
# advertise'ит — git не пушит ВООБЩЕ НИЧЕГО (`fatal: the receiving end does not support
# --atomic push`, rc 128, ни одного рефа) — то есть до неатомарного push'а он молча НЕ
# опускается; это ИЗМЕРЕНО (`receive.advertiseAtomic=false` на стенде), а не выведено из
# документации. Отказ приходит с ЧИСТЫМ состоянием и попадает в перепроверку
# ниже, у которой на него есть красная ветка. GitHub эту возможность advertise'ит —
# измерено двумя независимыми каналами: чтением
# `https://github.com/<repo>.git/info/refs?service=git-receive-pack` — тот самый HTTPS,
# которым пушит actions/checkout, — и живым `git push --atomic --dry-run`, прошедшим
# клиентскую проверку возможности. Второй замер сделан по SSH, поэтому вместе они говорят
# «возможность объявлена по HTTPS» и «клиент её принимает», но НЕ «атомарный push по HTTPS
# прогнан целиком»: настоящий push в этот репозиторий стендом не воспроизводим. Пин на
# безопасность отказа — стендовый тест с `receive.advertiseAtomic=false`.
#
# КАНАЛ В ЭТУ ПАЧКУ НАМЕРЕННО НЕ ВХОДИТ. Третий рефспек синтаксически возможен (тот же
# remote, а форса после #737 нет ни в одном push'е этого шага), но измерен так: при канале,
# указанном РУКОЙ вне main — задокументированная цена #737, — трёхрефовый atomic отбивает ВСЁ
# (`error: atomic push failed for ref refs/heads/stable`), main остаётся на своём sha и
# тега нет. При раздельном канале в том же состоянии bump и тег уезжают, а красным падает
# только канал: слияние заморозило бы ВЕРСИИ ЦЕЛИКОМ, и на каждом следующем релизе, пока
# человек не поправит канал.
#
# ЦЕНА РАЗМЕНА — остаточное полу-состояние «bump и тег есть, канал не двинулся», и лечится
# оно НЕ ВСЕГДА, поэтому два случая разведены, а не сложены в одно слово. Когда канал просто
# ОТСТАЛ (его нет вовсе / он предок моего bump'а), следующее приземление его догоняет —
# перемерено на обеих формах: следующий job уходит в rc=0, `merge-base --is-ancestor <мой
# bump> stable` отвечает 0, и на remote лежат ОБА тега, то есть пропущенной версии тут не
# возникает. А когда канал уведён РУКОЙ вне main, не лечится ничем: ff-only отобьёт push и на
# следующем релизе тоже, и так до ручной починки — ровно та цена, которую #737 назвала своей.
# Различает эти два случая та же градация ниже; отказ в обоих громкий и с командой в тексте.
#
# ПОРЯДОК ВОПРОСОВ В ПЕРЕПРОВЕРКЕ НЕСУЩИЙ, и он тот же, что CLAUDE.md уже предписывает
# агентам на отбитом push'е: СПЕРВА «а не приземлилось ли?», и только потом «кто меня
# накрыл». Круг 1 этой карточки задавал ВТОРОЙ вопрос, не задав ПЕРВОГО, и на этом
# терял релиз ЦЕЛИКОМ: сервер принимает ref и роняет соединение уже на ответе (502,
# «the remote end hung up unexpectedly»), клиент честно печатает отказ — а вершиной
# main оказывается МОЙ СОБСТВЕННЫЙ приземлившийся bump. Он отличен от $GITHUB_SHA и
# содержит его, то есть под «меня накрыли» подходит идеально; job уходил в ЗЕЛЁНЫЙ
# skip, не создав тега и не двинув stable. Ни второго актора, ни человека, ни второй
# попытки этому пути не нужно — воспроизведено на стенде шимом «push приземлился,
# клиент отчитался отказом» (tracker #716, круг 2).
#
# ЧЕСТНАЯ ЦЕНА перепроверки: про НЕ-гоночные отказы она по-прежнему не спрашивает
# «почему git отказал» — читать текст отказа нельзя, он зависит от версии git и локали.
#
# ПРОГЛАТЫВАНИЙ ЧЕТЫРЕ, и счёт тут ПЕРЕСЧИТЫВАЛСЯ на каждом круге, а не наследовался:
# круг 1 #716 писал «два», круг 2 починил одно (то самое выше) и нашёл вторым проходом ещё
# два, а ВТОРОЙ проход доработки построил четвёртое — и заодно опроверг утверждение, которым
# (2) закрывалась («первый прогон ГРОМКИЙ»). Затем #740 закрыла (2) и (4) ОДНИМ гейтом
# честности (см. `skip_or_refuse`), потому что после #723 у них одна и та же форма состояния
# и отличаются они лишь тем, ЧЕЙ job умер. **«Закрыто» тут не значит «класса больше нет», и
# СЧИТАТЬ оставшиеся одним числом поэтому нельзя:** закрыта та ФОРМА вершины, которую строит
# сам этот скрипт, — bump С ТЕГОМ; bump БЕЗ тега (сервер соврал про `atomic`; человек стёр
# тег) глотается по-прежнему и запинен отдельно, как остаток. Открытыми целиком остаются (1)
# и (3). Все четыре измерены на стенде, и закрытые оставлены в перечислении вместе с их
# конструкцией: держит их пин, а не эта проза, и следующая правка обязана видеть, ЧТО именно
# держится. Гейтов при этом ДВА, и проглатывания распределены по ним неравномерно —
# сказано у каждого.
#   (1) ПЕРЕПРОВЕРКА. Отказ по НЕ-гоночной причине (права, защита ветки), СОВПАВШИЙ с
#   приземлением сиблинга, уходит в зелёный skip. Смягчение ИЗМЕРЕНО, и оно слабее, чем
#   писал круг 1 («у ВЕРШИНЫ сиблинга нет ПО ОПРЕДЕЛЕНИЮ» — универсал шире замера).
#   Замер: при стоячем запрете push'а и приземлении в окне КАЖДОГО job'а серия из пяти
#   дала ЧЕТЫРЕ зелёных проглатывания и ОДИН красный — последний. То есть смягчение
#   даёт один красный на СЕРИЮ, а не на job: сломанный релизный путь остаётся замечен,
#   но по одному сигналу, а не по каждому. Гейт честности #740 стоит и на этой ветке
#   (перепроверка зовёт тот же `skip_or_refuse`), но КЛАССА не закрывает и не претендует:
#   он спрашивает про состояние ВЕРШИНЫ, а не про причину отказа git. Пересечение при этом
#   ЕСТЬ, и врать про него не надо: когда не-гоночный отказ совпал с приземлением, которое
#   само оказалось полу-релизом (bump с тегом, канал отстал), job теперь КРАСНЕЕТ — лучше,
#   но это заслуга формы вершины, а не разбора причины отказа. Совпало с обычным
#   таск-коммитом — по-прежнему зелёный skip, то есть класс жив. Что перепроверка ходит
#   через гейт, а не мимо, держит не «зелёный сосед», а мутация: снять маршрутизацию — и
#   краснеет test_without_the_landed_question_the_release_is_lost (1 failed при control
#   0 failed), тогда как test_lost_race_after_the_pre_push_check_still_skips эту ветку
#   ПРОХОДИТ, но остаётся зелёным и потому доказательством не является.
#   (2) ЗАКРЫТО #740 В ФОРМЕ «BUMP С ТЕГОМ». ПРЕДТЕГОВОЙ гейт, КЛАСС: любое
#   полу-собранное состояние +
#   ПЕРЕЗАПУСК = зелёный skip. Job, оставивший свой bump вершиной main (убит между
#   атомарным push'ем и push'ем канала — или между ним и локальным `git branch -f`,
#   который тоже умеет упасть), при перезапуске читал вершину как «меня накрыли» — накрыл
#   собственный осиротевший bump — и зеленел. Первый прогон ЭТОГО ЖЕ job'а при этом
#   ГРОМКИЙ (exit 1), и тихо он становился только после ручного `gh run rerun` — но
#   читать это как «полу-состояние всегда сначала шумит» НЕЛЬЗЯ: оговорка держалась на
#   том, что вершина — МОЙ СОБСТВЕННЫЙ bump, а чужие приземления под тем же
#   полу-состоянием глотались с ПЕРВОГО прогона, и это было отдельное проглатывание (4).
#   ФОРМА этого полу-состояния с #723 ровно одна — bump И ТЕГ на remote, не двинут ровно
#   `stable`: «bump без тега» этот скрипт больше не строит (пока сервер держит `atomic`),
#   а круг 1 описывал класс ещё уже («не доделав ни тег, ни stable»). Ровно эта форма и
#   провалила оба доказательства гейта честности, поэтому перезапуск теперь КРАСНЫЙ —
#   пин test_a_rerun_over_its_own_orphan_bump_is_no_longer_green. Оговорка ровно та же, что
#   у (4): вершина без тега (сервер соврал про `atomic`, человек стёр тег) проходит P2
#   честно, и там перезапуск снова зелен — test_an_untagged_orphan_bump_still_swallows.
#   Чинить он по-прежнему
#   ничего не чинит (канал стоит), но и не стирает единственный красный, который у этого
#   состояния был: `gh run rerun` ПЕРЕПИСЫВАЕТ вердикт того же прогона. Перезапуск не
#   спасает и ПЕРВЫЙ вопрос, и это правильно: он коммитит СВОЙ bump (другая
