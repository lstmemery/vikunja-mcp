#   тем, что вершина здесь BUMP-коммит, у которого прогона НЕ БЫВАЕТ ВООБЩЕ (перемерено:
#   60 из 60 подряд bump-sha отдают `[]`), так что «её прогон красный» неприменимо — job,
#   который должен был её выпустить, уже отработал и умер. Один обрыв давал столько
#   зелёных проглатываний, сколько приземлений он накрыл (замерено ДВА на трёх коммитах).
#   И внесено это было ГЕЙТОМ, а не унаследовано: на одном и том же входе до-716 инлайн
#   даёт `! [rejected] … (non-fast-forward)` exit 1, круг 1 — rc=0, круг 2 — rc=0.
#   Теперь тот же вход красный, а на remote при этом не меняется НИ ОДИН реф — пин
#   test_a_foreign_orphan_bump_no_longer_swallows_an_earlier_landing, мутационный сосед
#   test_without_the_honest_skip_gate_the_foreign_orphan_swallows_again возвращает
#   проглатывание дословно. ЧЕГО ЗАКРЫТИЕ НЕ ОЗНАЧАЕТ, два пункта, оба измеренные.
#   Во-первых, канал в этот момент всё ещё отстал, красный лишь называет это вслух —
#   и «догонит следующее приземление» верно ровно тогда, когда канал просто ОТСТАЛ:
#   пин прогоняет эту форму, а если push канала кто-то ОТБИВАЕТ, следующее приземление
#   упирается в тот же отказ. Во-вторых, закрыт вход с ТЕГОМ на вершине; тот же
#   осиротевший bump БЕЗ тега глотается по-прежнему, и это отдельный пин-остаток
#   test_an_untagged_orphan_bump_still_swallows.
# Рефспеки ПОЛНЫЕ по той же причине, что и у fetch выше: короткое `HEAD:main` при
# существующем теге `main` git отвергает как `dst refspec main matches more than one`,
# а короткое `origin stable`/`origin vX.Y.Z` так же неоднозначно с обеих сторон.
if ! git push --atomic origin "HEAD:refs/heads/${MAIN_BRANCH}" \
        "refs/tags/${VERSION}:refs/tags/${VERSION}"; then
    head=$(git rev-parse HEAD)
    if ! read_tip; then
        # Не «main всё ещё на моём sha»: спросить не удалось вовсе. Говорим это.
        echo "push to ${MAIN_BRANCH} failed and the tip could not be read" >&2
        exit 1
    fi
    if [ "$tip" = "$head" ]; then
        # ВОПРОС ПЕРВЫЙ: приземлилось. Раз main взят, то тег обязан быть взят ВМЕСТЕ с ним —
        # это ровно то, что покупает `--atomic`, и ровно поэтому отдельного push'а тега ниже
        # больше нет. Но это ЕДИНСТВЕННАЯ ветка после отбитого push'а, которая уходит в
        # ЗЕЛЁНОЕ, а весь смысл перепроверки — «не верь коду возврата, СПРОСИ У REMOTE».
        # Спрашивать только про main и про тег верить на слово значило бы держать зелень на
        # предположении о чужом сервере: атакующий проход построил сервер, который atomic
        # ОБЪЯВЛЯЕТ, берёт ветку, тег роняет и врёт отказом, — и получил rc 0 с релизом без
        # тега (до #723 отдельный push тега это чинил). Спрашиваем и про тег; «не смог
        # спросить — не решай» тут то же, что у main и у канала.
        if ! read_tag || [ "$tag_commit" != "$head" ]; then
            echo "push to ${MAIN_BRANCH} reported failure and ${head} IS on ${MAIN_BRANCH}," \
                 "but tag ${VERSION} does not point at it on origin (or could not be read):" \
                 "the push was accepted NON-atomically. Channel NOT moved" >&2
            exit 1
        fi
        echo "::notice::main push reported failure but landed: main is at $head; finishing the release"
        echo "main push reported failure but landed: main is at $head; finishing the release"
    elif git merge-base --is-ancestor "$head" "$tip"; then
        # Приземлилось (значит и тег тоже), но поверх УЖЕ легло что-то новее, и канал я не
        # двигал. Формулировка тут МЕНЯЛАСЬ ДВАЖДЫ, и оба раза потому, что становилась
        # ложной. #737 обнулил первое обоснование («push -f на stable откатил бы канал
        # назад»): форса на канале больше нет, ff-only отбил бы push, а градация отдала бы
        # зелёный notice. #723 обнулил второе — «тега на remote нет»: под `--atomic` тег
        # уехал вместе с bump'ом, и текст «tag NOT pushed» стал ВРАНЬЁМ в логе job'а.
        # Красным это остаётся по правилу репозитория — ЗВУК ВАЖНЕЕ ТИШИНЫ: канал не
        # двинут, релиз собран не до конца. Довести его отсюда (пока канал не ушёл дальше
        # моего bump'а, ff-only на него — законный ход ВПЕРЁД, даже если вершина main уже
        # дальше; ушёл — об этом скажет градация канала ниже) НАМЕРЕННО не делается:
        # это превратило бы красное в зелёное на состоянии, про которое скрипт не знает,
        # кто выпустит вершину, — то самое предсказание, которого `skip()` не даёт.
        echo "push to ${MAIN_BRANCH} reported failure, yet ${head} IS on ${MAIN_BRANCH}" \
             "with a newer tip ${tip} on top: tag ${VERSION} pushed with it," \
             "stable NOT moved" >&2
        exit 1
    elif superseded_by_neighbour; then
        # ВОПРОС ВТОРОЙ, и только теперь: моего bump'а на main нет, а сосед приземлился.
        # Гейт честности тут ТОТ ЖЕ и по той же причине, по которой строка решения одна на
        # оба гейта: состояние, в которое я попадаю, — то же самое (вершина содержит меня, я
        # ничего не запушил), значит и вопрос к нему тот же.
        skip_or_refuse
    else
        echo "push to ${MAIN_BRANCH} failed and no newer landing containing ${GITHUB_SHA} was seen" >&2
        exit 1
    fi
fi

# Хвост, общий ОБОИМ путям: и обычному, и ветке «приземлилось». Push'ей тут остался ОДИН —
# тег уехал вместе с bump'ом атомарно (#723). `git branch -f` — операция ЛОКАЛЬНАЯ, не push:
# remote её не видит, а упасть она может только по локальной причине — на стенде вышло двумя
# (незаписываемый реф; ветка `stable`, вычекаученная в каком-нибудь worktree, — тут git
# отказывает ДО всякой записи), и любая из них уже громкая через `set -eu`.
git branch -f "${STABLE_BRANCH}" HEAD                         # ЛОКАЛЬНО: stable -> мой bump

# КАНАЛ ДВИГАЕТСЯ ТОЛЬКО ВПЕРЁД, и держит это отсутствие `-f`: push без него —
# fast-forward-only, то есть git САМ отказывается перевести stable на коммит, который не
# содержит текущей вершины канала. До #737 здесь стоял безусловный `git push -f`, и
# измеренная цена этого была такой: между решением job'а релизиться и этим push'ем есть
# окно, и полный релиз сиблинга, впихнутый стендом в него, ОТКАТЫВАЛ канал назад —
# одинаково на ветке «приземлилось», на обычном пути этого же скрипта и на до-716 инлайне
# из ci.yml (все три ряда: job ЗЕЛЁНЫЙ, теги [v0.2.171 v0.2.172] на месте, а `stable`
# уезжает на МОЙ bump 0.2.171, хотя вершина main уже 0.2.172). Работа при этом не
# теряется — следующее приземление двигает канал вперёд, — но до него потребители тянут
# код на патч СТАРШЕ, чем говорит последний тег.
#
# ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ — `--force-with-lease` БЕЗ АРГУМЕНТА (голый флаг: величину
# для сравнения он берёт из `refs/remotes/origin/stable`). Он выглядит точной заменой,
# и ПЕРВЫЙ из трёх замеров — в его пользу, так что начинаем с него.
#   (1) Реф `refs/remotes/origin/stable` на раннере ЕСТЬ. Измерено логом шага
#       `Run actions/checkout@v4` того самого job'а `release`, который и делает push'и
#       (job 91562691267 прогона 30772730104 — релиз коммита ad41397, ПЕРВОГО
#       приземления этой карточки): при `fetch-depth: 0` checkout зовёт
#       `git -c protocol.version=2 fetch --prune --no-recurse-submodules origin
#       +refs/heads/*:refs/remotes/origin/* +refs/tags/*:refs/tags/*` и печатает
#       `* [new branch] stable -> origin/stable`. Не единичный прогон: та же строка в
#       job'е 91515383221 прогона 30754732335, и он покрывает ВТОРУЮ конфигурацию —
#       «вершина ≠ триггерный sha». Там в момент fetch'а `origin/main` был `dff2def0`,
#       а ТРИГГЕРНЫЙ sha job'а — `0664256f` (сам job не выпустил НИЧЕГО: он умер на
#       `fatal: tag 'v0.2.171' already exists` ещё до первого push'а — это и есть
#       случай #716), поэтому checkout делает ВТОРОЙ, целевой fetch
#       `git -c protocol.version=2 fetch --no-tags --prune --no-recurse-submodules
#       origin +0664256f…:refs/remotes/origin/main`, и тот ФОРСОМ переписывает только
#       `origin/main` (`+ dff2def...0664256 … (forced update)`), а `origin/stable`,
#       созданный первым fetch'ем, остаётся: `--prune` в этом job'е не удалил ни одного
#       рефа (ноль строк `[deleted]`). Значит на раннере голый lease имел бы свою
#       величину и ЭТУ гонку отбил бы. (Здесь стояло «создаёт ли checkout этот реф, НЕ
#       измерено» — с тех прогонов это ложь, и держать её нельзя: она читается как
#       «вопрос открыт», а он закрыт.) ЧЕСТНАЯ ГРАНИЦА второго свидетеля: он добавляет
#       вторую КОНФИГУРАЦИЮ, но не вторую ВЕРСИЮ экшена — оба прогона тянули один и тот
#       же `actions/checkout@v4`, `SHA:11d5960a326750d5838078e36cf38b85af677262`, в один
#       день, а спорит возражение (2) как раз про версии.
#   (2) Почему это возражения не снимает: рефспек задаёт ЭКШЕН, а не мы, а `ci.yml`
#       подписан на ПЛАВАЮЩИЙ `@v4` — значит рефспек может смениться с любым обновлением
#       этого тега, и запинить его можно ровно одним способом, которого этот репозиторий
#       не делает: пригвоздить экшен по sha. Цена смены при этом не «гонка проскочит», а
#       «КАЖДЫЙ релиз красный»: БЕЗ этого рефа голый lease отбивает даже СОВЕРШЕННО
#       НОРМАЛЬНЫЙ push, на прогоне без всякой гонки (`! [rejected] … (stale info)`,
#       rc=1 — замерено стендом).
#   (3) И даже С рефом голый lease обнуляет обычный `git fetch origin` перед push'ем
#       (замерено: откат проходит, rc=0), потому что fetch обновляет ровно ту величину,
#       которую lease и сравнивает. Сегодня такого fetch'а до push'а канала в этом файле
#       нет — оба, что стоят раньше (`superseded`→`read_tip` и `read_tip` в ветке
#       отбитого push'а в main), читают `refs/heads/main`, а единственный по
#       `refs/heads/stable` (`read_channel`) стоит уже ПОСЛЕ отказа. Но это свойство
#       текущего текста, а не гарантия.
#   ЯВНАЯ форма (`--force-with-lease=refs/heads/stable:<sha>`) от tracking-рефа не
#   зависит, и (2)-(3) к ней НЕ относятся. Отвергнута она не замером, а разбором того,
#   КАКОЙ вопрос задаёт каждая проверка: lease спрашивает «изменилось ли что-нибудь с
#   тех пор, как я посмотрел», а нужен ответ на «содержит ли новое значение текущее».
#   Совпадают они, только если посмотреть успели ДО сиблинга; посмотрев ПОСЛЕ, ты
#   возьмёшь в аренду уже уехавший вперёд канал — lease согласится, и форс сделает ровно
#   тот откат, ради которого всё это писано.
# У push'а без `-f` нужный вопрос задаётся ВСЕГДА и не зависит ни от того, когда ты
# смотрел, ни от чужого рефспека: сравнение делает СЕРВЕР по тому, что он сейчас
# advertise'ит, и замер даёт один и тот же отказ и с tracking-рефом, и без него.
#
# Отказ ГРАДУИРУЕТСЯ перепроверкой той же ФОРМЫ, что стоит на push'е в main, и по той же
# причине: читать ТЕКСТ отказа git нельзя. Но параллель на этом кончается, и растягивать
# её нельзя — ниже две поправки, обе измеренные.
#   ВЕРДИКТ здесь ОДИН, а сообщений два. `git merge-base --is-ancestor X X` отвечает 0
#   (проверено), поэтому ветвь равенства ПОГЛОЩЕНА ветвью предка: снять её — и job
#   останется зелёным, изменится только текст в логе. Ветвь оставлена именно ради текста:
#   «твой push всё-таки приземлился» и «тебя увёз более новый релиз» — разные новости для
#   человека, читающего job. Тест на неё это и пинит — СООБЩЕНИЕ, не исход.
#   ИСХОДЫ у main и у канала на одинаковом вопросе РАЗНЫЕ: у main «уехало, но поверх легло
#   новее» значит канал не двинут (тег-то с #723 уехал вместе с bump'ом), то есть
#   полу-собранный релиз (красное), а у канала
#   «он уже впереди и содержит меня» значит релиз состоялся ЦЕЛИКОМ, просто более новым
#   job'ом (зелёное). Зелёной ветвь становится ТОЛЬКО с
# доказательством, что канал уже несёт мой bump (равенство или `--is-ancestor`); всё
# остальное — включая «прочитать канал не удалось» — КРАСНОЕ. Тихого не-сдвига ЭТОТ БЛОК
# поэтому не добавляет: ни на одной ЕГО ветке состояние «канал не двинулся И моего кода в
# нём нет» зелёным не бывает.
#
# ШИРЕ ЭТОГО БЛОКА так сказать НЕЛЬЗЯ, и второй проход построил ровно контрпример: зелёный
# job с неподвинутым каналом и без моего кода в нём даёт ПРЕДТЕГОВЫЙ гейт — это его
# проглатывания выше. Список с тех пор УКОРОТИЛСЯ, а утверждение осталось верным: «самое
# бытовое» из него ушло (раннера убили между push'ями, потом `gh run rerun` — это (2), и
# #740 сделала его красным), но (1) и (3) на месте, и контрпример строится по любому из
# них. Класс пре-существующий (#723, #740), этой правкой не внесён и не закрыт;
# она снимает ОТКАТ канала, а не весь класс «канал отстал при зелёном job'е».
#
# И ЦЕНА, названная прямо: канал, указанный РУКОЙ на коммит вне main, теперь не
# перетирается молча, а КРАСНИТ каждый следующий релиз, пока человек его не поправит
# (пин — test_a_channel_pointed_off_main_is_loud_rather_than_overwritten). Ни одна
# процедура репозитория такого состояния не создаёт: задокументированный откат целится в
# ТЕГ, а тег всегда предок вершины.
#
# ЧЕГО ЭТО НЕ ЧИНИТ, ЧТОБЫ НЕ ПОКАЗАЛОСЬ, ЧТО ЧИНИТ: человеческий откат канала
# (`git branch -f stable vX.Y.Z && git push -f origin stable`), сделанный ВНУТРИ окна
# идущего релизного job'а, этот job по-прежнему молча отменяет — старый тег является
# ПРЕДКОМ моего bump'а, значит мой push остаётся честным fast-forward'ом и проходит.
# Отдельно, чтобы «внутри окна» не прочиталось как «а снаружи откат живёт вечно»: снаружи
# канал тоже уедет вперёд — на СЛЕДУЮЩЕМ приземлении, и это задуманное поведение (откатили,
# починили, приземлили). Разница в том, ЧЬЯ работа его двигает: снаружи — новая, внутри
# окна — старая, стартовавшая ДО отката. Измерено обе стороны; то же измерение — и всё, что
# сказано про «не ломает процедуру»: релиз после отката проходит, rc=0, канал снова едет
# вперёд. Долговечности самого отката тут никто не обещает — её нет ни до #737, ни после.
if ! git push origin "refs/heads/${STABLE_BRANCH}:refs/heads/${STABLE_BRANCH}"; then
    head=$(git rev-parse HEAD)
    if ! read_channel; then
        # Не «канал остался на месте»: спросить не удалось вовсе. Говорим это.
        echo "push to ${STABLE_BRANCH} failed and ${STABLE_BRANCH} could not be read" \
             "(no such ref on origin, or the fetch itself failed)" >&2
        exit 1
    fi
    if [ "$channel" = "$head" ]; then
        # ВОПРОС ПЕРВЫЙ: приземлилось (тот же обрыв на ответе, что чинится у main выше).
        echo "::notice::${STABLE_BRANCH} push reported failure but landed: it is at $head"
        echo "${STABLE_BRANCH} push reported failure but landed: it is at $head"
    elif git merge-base --is-ancestor "$head" "$channel"; then
        # ВОПРОС ВТОРОЙ: канал уже ВПЕРЕДИ и содержит меня — его двинул более новый релиз.
        # Двигать его на мой bump значило бы откатить потребителей на патч назад.
        echo "::notice::${STABLE_BRANCH} is already at $channel, which contains $head; not moved backwards"
        echo "${STABLE_BRANCH} is already at $channel, which contains $head; not moved backwards"
    else
        echo "push to ${STABLE_BRANCH} failed and ${STABLE_BRANCH} ($channel) does not contain" \
             "${head}: tag ${VERSION} pushed, channel NOT moved." \
             "Fix by hand: git branch -f ${STABLE_BRANCH} ${VERSION} &&" \
             "git push -f origin ${STABLE_BRANCH}" >&2
        exit 1
    fi
fi
