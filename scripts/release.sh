# Проверка ПЕРЕД `git tag`: тег создаётся локально, но `git tag -a` на занятом имени
# падает кодом 128 — то есть без этого гейта отставший job умирает раньше, чем успевает
# заметить, что релиз ему уже не нужен.
if superseded; then
    skip_or_refuse
fi

