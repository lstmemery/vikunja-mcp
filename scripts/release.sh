#!/bin/sh
# Релизный шаг авто-патча: bump-коммит -> main, неизменяемый тег vX.Y.Z, канал stable.
#
# ПОЧЕМУ ЭТО ФАЙЛ, А НЕ `run: |` В ci.yml. Релизный путь чинится ЗАМЕРОМ, а не
# рассуждением: инлайновый YAML-шаг нечем прогнать нигде, кроме самого CI, то есть
# нечем и проверить до раскатки на всех потребителей канала `stable`. Отдельный файл
# гоняется на стенде (bare-origin + клоны) и пинится юнит-тестом
# `tests/unit/test_release_script.py`, который запускает ИМЕННО ЭТОТ файл.
#
# ВХОД (env):
#   VERSION      — `vX.Y.Z`, последняя строка stdout у scripts/bump_version.py;
#   GITHUB_SHA   — коммит, НА КОТОРЫЙ сработал триггер (его же чекаутит
#                  actions/checkout@v4, поэтому он же — родитель bump-коммита).
# cwd — чекаут этого sha с уже сбампленными version-файлами.
set -eu

: "${VERSION:?VERSION (vX.Y.Z) is required}"
: "${GITHUB_SHA:?GITHUB_SHA is required}"

MAIN_BRANCH=main

# «Меня уже накрыли»: вершина main ОТЛИЧНА от моего sha и при этом СОДЕРЖИТ его —
# значит поверх меня уже приземлился более новый коммит, а мой bump лечь на main больше
# не может (он сидит поверх НЕ-вершины). Делать мне тут нечего (tracker #716).
# Дальше этого утверждение НЕ идёт, и намеренно: «релиз сделает ЕГО job, а мой коммит
# уедет в stable вместе с его bump'ом» — предсказание, а не знание, и в ТРЁХ из ЧЕТЫРЁХ
# названных ниже проглатываний оно ЛОЖНО. Ровно этот хвост круг 2 убрал и отсюда, и из
# notice.
#
# Именно это условие, а не «тег занят»: занятое имя тега — лишь СИМПТОМ. Два job'а,
# чекаутящие РАЗНЫЕ sha с одинаковыми version-файлами, считают один и тот же следующий
# патч; переименовать версию мало — bump отставшего сидит поверх НЕ-вершины, поэтому
# `git push origin HEAD:main` у него всё равно non-fast-forward.
#
# Условие НАМЕРЕННО узкое — «не смог» и «не нужно» обязаны выглядеть по-разному, —
# но «всё остальное красное» из него НЕ следует, и обе оговорки ИЗМЕРЕНЫ, а не
# выведены. (1) main, откаченный force-push'ем НАЗАД, под условие не подходит (старая
# вершина — ПРЕДОК моего sha), поэтому job едет дальше и fast-forward'ом пушит bump
# поверх отката — ровно как делал этот шаг ДО гейта, байт-в-байт тот же исход на
# стенде с гейтом и без него. (2) отказ push'а по НЕ-гоночной причине разбирается
# ниже, у самой перепроверки, и там он честно назван проглатыванием.

# Спросить вершину. Отдаёт её ГЛОБАЛЬНО в $tip; код 1 = «спросить НЕ УДАЛОСЬ».
#
# Рефспек ПОЛНЫЙ, и это не педантизм: `git fetch origin main` резолвит имя по всем
# пространствам имён, поэтому аннотированный ТЕГ с именем `main` уводит fetch на себя.
# Дальше ловушка захлопывается тихо: `rev-parse FETCH_HEAD` отдаёт объект тега (он НЕ
# равен sha коммита), а `merge-base --is-ancestor` его разыменовывает и честно отвечает
# «X предок X» — гейт получает «меня накрыли» на вершине, которая РОВНО мой коммит, и
# релиз молча не состоится. Измерено; поэтому же `^{commit}`.
#
# «Не смог спросить — не решай»: `set -e` внутри функции, чей код проверяет `if`, НЕ
# действует, поэтому каждый шаг обязан сказать «нет» САМ. Точек отказа три (`|| return 1`
# у fetch, `|| return 1` у rev-parse и то, что `merge-base --is-ancestor` с ПУСТЫМ
# аргументом отвечает «нет»), и КАКАЯ ИЗ НИХ ДЕРЖИТ — зависит от формы отказа. Измерено
# на git 2.50.1 (Apple Git-155), обе формы:
#   СЕТЕВЫЕ (нет remote, remote не репозиторий, объекты нечитаемы, рефа нет) — git
#   УСЕКАЕТ FETCH_HEAD в 0 байт, поэтому падает уже `rev-parse`, а первая строка тут
#   защита в глубину. Ровно поэтому мутация, снимающая её, ДОЛГО не убивала ни одного
#   теста: все стендовые отказы были сетевыми.
#   ЗАПИСЬ (FETCH_HEAD нельзя перезаписать): `error: cannot open '.git/FETCH_HEAD':
#   Permission denied`, rc=255, а файл остаётся ПРЕЖНИМ — `rev-parse` отдаёт код 0 и
#   УСТАРЕВШУЮ вершину. Здесь `|| return 1` у fetch — ЕДИНСТВЕННОЕ, что стоит между
#   протухшими данными и решением, и это НЕ теоретизирование: тест
#   test_a_stale_fetch_head_never_decides строит ровно это и краснеет от снятия строки
#   (control 0 failed -> 1 failed). Поэтому «упавший fetch усекает FETCH_HEAD» — НЕ
#   универсалия, и лишних точек тут нет ни одной.
# Второй тест, test_a_fetch_that_cannot_answer_is_never_a_skip, пинит наблюдаемое
# СВОЙСТВО поверх этого: не сумевший ответить fetch НИКОГДА не даёт skip.
read_tip() {
    git fetch --quiet origin "refs/heads/${MAIN_BRANCH}" || return 1
    tip=$(git rev-parse "FETCH_HEAD^{commit}") || return 1
}

# ЕДИНСТВЕННАЯ строка решения «меня накрыл СОСЕД» — одна на оба гейта, чтобы мутация
# в tests/unit/test_release_script.py снимала защиту целиком, а не половину.
superseded_by_neighbour() {
    [ "$tip" != "$GITHUB_SHA" ] && git merge-base --is-ancestor "$GITHUB_SHA" "$tip"
}

superseded() {
    read_tip || return 1
    superseded_by_neighbour
}

# Формулировка НАМЕРЕННО сужена до того, что скрипт ЗНАЕТ, и с #716-круга-2 сужена
# ЕЩЁ РАЗ. Прежний хвост «releasing it is that newer tip's job» назывался «тем, что мы
# знаем», а был предсказанием — и ложен он в ТРЁХ из ЧЕТЫРЁХ проглатываний ниже: в (2)
# и в (4) вершина — bump-коммит, а на bump-коммитах прогонов НЕ БЫВАЕТ (по построению:
# GITHUB_TOKEN не ретриггерит CI, плюс ci-skip-маркер; перемерено доработкой на 60
# подряд bump-sha — у всех `gh run list --commit <полный sha>` отдаёт `[]`), а в (3)
# прогон у вершины есть, но он не выпускает релиз. Знаем мы ровно одно: вершина уже
# содержит нас, и мы ничего не запушили. Ровно это обе строки и говорят — ОДИНАКОВО.
skip() {
    echo "::notice::release skipped: main is at $1, which already contains $GITHUB_SHA; nothing pushed"
    echo "release skipped: main is at $1, which already contains $GITHUB_SHA; nothing pushed"
}

git add pyproject.toml src/vikunja_mcp/__init__.py uv.lock
git commit -m "chore: ${VERSION} [skip ci]"

# Проверка ПЕРЕД `git tag`: тег создаётся локально, но `git tag -a` на занятом имени
# падает кодом 128 — то есть без этого гейта отставший job умирает раньше, чем успевает
# заметить, что релиз ему уже не нужен.
if superseded; then
    skip "$tip"
    exit 0
fi

git tag -a "${VERSION}" -m "${VERSION}"

# Пуш в main — ПЕРВЫЙ из четырёх и точка линеаризации: выиграть его может ровно один
# job на вершину, а тег и stable пушатся только после победы. Остаточное окно между
# проверкой выше и этим push'ем закрывается ПЕРЕПРОВЕРКОЙ, а не молчаливым ретраем.
#
# ПОРЯДОК ВОПРОСОВ В ПЕРЕПРОВЕРКЕ НЕСУЩИЙ, и он тот же, что CLAUDE.md уже предписывает
# агентам на отбитом push'е: СПЕРВА «а не приземлилось ли?», и только потом «кто меня
# накрыл». Круг 1 этой карточки задавал ВТОРОЙ вопрос, не задав ПЕРВОГО, и на этом
# терял релиз ЦЕЛИКОМ: сервер принимает ref и роняет соединение уже на ответе (502,
# «the remote end hung up unexpectedly»), клиент честно печатает отказ — а вершиной
# main оказывается МОЙ СОБСТВЕННЫЙ приземлившийся bump. Он отличен от $GITHUB_SHA и
# содержит его, то есть под «меня накрыли» подходит идеально; job уходил в ЗЕЛЁНЫЙ
# skip, не создав тега и не двинув stable. Ни второго актора, ни человека, ни второй
# попытки этому пути не нужно — воспроизведено на стенде шимом «push приземлился,
# клиент отчитался отказом» (tracker #716, круг 2).
#
# ЧЕСТНАЯ ЦЕНА перепроверки: про НЕ-гоночные отказы она по-прежнему не спрашивает
# «почему git отказал» — читать текст отказа нельзя, он зависит от версии git и локали.
#
# ПРОГЛАТЫВАНИЙ ЧЕТЫРЕ, и счёт ПЕРЕСЧИТЫВАЛСЯ дважды, а не наследовался: круг 1 писал
# «два», круг 2 починил одно (то самое выше) и нашёл вторым проходом ещё два, а ВТОРОЙ
# проход доработки построил четвёртое — и заодно опроверг утверждение, которым (2)
# закрывалась («первый прогон ГРОМКИЙ»). Все четыре измерены на стенде, и все четыре
# лучше знать заранее, чем обнаружить. Гейтов при этом ДВА, и проглатывания распределены
# по ним неравномерно — сказано у каждого.
#   (1) ПЕРЕПРОВЕРКА. Отказ по НЕ-гоночной причине (права, защита ветки), СОВПАВШИЙ с
#   приземлением сиблинга, уходит в зелёный skip. Смягчение ИЗМЕРЕНО, и оно слабее, чем
#   писал круг 1 («у ВЕРШИНЫ сиблинга нет ПО ОПРЕДЕЛЕНИЮ» — универсал шире замера).
#   Замер: при стоячем запрете push'а и приземлении в окне КАЖДОГО job'а серия из пяти
#   дала ЧЕТЫРЕ зелёных проглатывания и ОДИН красный — последний. То есть смягчение
#   даёт один красный на СЕРИЮ, а не на job: сломанный релизный путь остаётся замечен,
#   но по одному сигналу, а не по каждому.
#   (2) ПРЕДТЕГОВОЙ гейт, КЛАСС: любое полу-собранное состояние + ПЕРЕЗАПУСК = зелёный
#   skip. Job, оставивший свой bump вершиной main (убит между push'ями; или push тега
#   приземлился, а клиент отчитался отказом — тот же обрыв, что чинится выше, только на
#   push'е №2), при перезапуске читает вершину как «меня накрыли» — накрыл собственный
#   осиротевший bump — и зеленеет. Первый прогон ЭТОГО ЖЕ job'а при этом ГРОМКИЙ
#   (exit 1), и тихо он становится только после ручного `gh run rerun` — но читать это
#   как «полу-состояние всегда сначала шумит» НЕЛЬЗЯ: оговорка держится на том, что
#   вершина — МОЙ СОБСТВЕННЫЙ bump. Чужие приземления под тем же полу-состоянием
#   глотаются с ПЕРВОГО прогона, и это отдельное проглатывание (4). Круг 1 описывал
#   класс уже, чем он есть («не доделав ни тег, ни stable»): если обрыв был на push'е
#   ТЕГА, тег на remote УЖЕ ЕСТЬ, и теряется ровно `stable`. Перезапуск не спасает
#   ПЕРВЫЙ вопрос, и это правильно: он коммитит СВОЙ bump (другая committer-date, другой
#   sha), поэтому «а не приземлилось ли МОЁ» отвечает «нет» честно. До гейта перезапуск
#   краснел (`fatal: tag … already exists`): состояние он не чинил, но был виден. #723.
#   (3) ПРЕДТЕГОВОЙ гейт: вершина, накрывшая меня, СВОЕГО релиза не сделает — её прогон
#   красный, её ci-skip-маркер проглочен, её job отменён. Тогда skip верен буквально
#   («поверх меня новее»), но релиза не будет ни у кого, и `stable` стоит. Это стендовый
#   CASE C, он же строка «тег СВОБОДЕН» в таблице карточки: до гейта тот же вход давал
#   `! [rejected] … (non-fast-forward)`, exit 1. Проверить это отсюда НЕЧЕМ — потому
#   `skip()` и не обещает, что вершину кто-то выпустит. Оценка частоты не выдумана: в
#   ночь на 31.07 семь прогонов main из пятнадцати подряд были красными.
#   (4) ПРЕДТЕГОВОЙ гейт, и это НЕ (2) и НЕ (3): вершину держит ЧУЖОЙ осиротевший bump,
#   а глотается ДРУГОЕ, более раннее приземление — на своём ПЕРВОМ и ЕДИНСТВЕННОМ
#   прогоне. Сиблинг умер между push'ями, его bump стал вершиной main и СОДЕРЖИТ мой
#   sha; гейт честно говорит «накрыли», job зеленеет, тега нет, `stable` стоит. От (2)
#   отличается тем, что перезапусков НОЛЬ и обрыв случился НЕ В МОЁМ прогоне (поэтому
#   оговорка «первый прогон громкий» сюда не достаёт); от (3) — тем, что вершина здесь
#   BUMP-коммит, у которого прогона НЕ БЫВАЕТ ВООБЩЕ (перемерено: 60 из 60 подряд
#   bump-sha отдают `[]`), так что «её прогон красный» неприменимо — job, который должен
#   был её выпустить, уже отработал и умер. Один обрыв даёт столько зелёных
#   проглатываний, сколько приземлений он накрыл (замерено ДВА на трёх коммитах). И это
#   ВНЕСЕНО гейтом, а не унаследовано: на одном и том же входе до-716 инлайн даёт
#   `! [rejected] … (non-fast-forward)` exit 1, круг 1 — rc=0, круг 2 — rc=0. Запинено
#   тестом test_a_foreign_orphan_bump_swallows_an_earlier_landing; класс — карточка #740.
# Рефспеки ПОЛНЫЕ по той же причине, что и у fetch выше: короткое `HEAD:main` при
# существующем теге `main` git отвергает как `dst refspec main matches more than one`,
# а короткое `origin stable`/`origin vX.Y.Z` так же неоднозначно с обеих сторон.
if ! git push origin "HEAD:refs/heads/${MAIN_BRANCH}"; then
    head=$(git rev-parse HEAD)
    if ! read_tip; then
        # Не «main всё ещё на моём sha»: спросить не удалось вовсе. Говорим это.
        echo "push to ${MAIN_BRANCH} failed and the tip could not be read" >&2
        exit 1
    fi
    if [ "$tip" = "$head" ]; then
        # ВОПРОС ПЕРВЫЙ: приземлилось. Тег и stable ещё не пушились — доводим релиз.
        echo "::notice::main push reported failure but landed: main is at $head; finishing the release"
        echo "main push reported failure but landed: main is at $head; finishing the release"
    elif git merge-base --is-ancestor "$head" "$tip"; then
        # Приземлилось, но поверх УЖЕ легло что-то новее. Тег не создан на remote, а
        # stable двигать нельзя: `git push -f` на stable откатил бы канал назад, если
        # job вершины уже успел его двинуть. Правило репозитория тут одно — ЗВУК ВАЖНЕЕ
        # ТИШИНЫ: состояние настоящее полу-собранное, и это ровно то, чем оно было ДО
        # всякого гейта (отбитый push = красный job). Разбор класса — #723.
        echo "push to ${MAIN_BRANCH} reported failure, yet ${head} IS on ${MAIN_BRANCH}" \
             "with a newer tip ${tip} on top: tag ${VERSION} NOT pushed, stable NOT moved" >&2
        exit 1
    elif superseded_by_neighbour; then
        # ВОПРОС ВТОРОЙ, и только теперь: моего bump'а на main нет, а сосед приземлился.
        skip "$tip"
        exit 0
    else
        echo "push to ${MAIN_BRANCH} failed and no newer landing containing ${GITHUB_SHA} was seen" >&2
        exit 1
    fi
fi

# Три последних push'а — общий хвост ОБОИХ путей: и обычного, и ветки «приземлилось».
# Между решением и `push -f` на stable есть окно, и оно НЕ введено этим гейтом: стенд
# впихнул в него ПОЛНЫЙ релиз сиблинга и получил один и тот же откат канала во всех трёх
# рядах — ветка «приземлилось», обычный путь этого же скрипта и до-716 инлайн из ci.yml
# (`stable` уезжает на МОЙ bump, хотя вершина main уже дальше). В проде окно закрывает
# `concurrency: group: release` в ci.yml: релизные job'ы сериализуются, поэтому чужой
# job внутрь моего окна не попадает — вот ГДЕ группа действительно несущая, в отличие от
# версионной гонки, которую она не чинит. Класс заведён карточкой #737.
git push origin "refs/tags/${VERSION}:refs/tags/${VERSION}"   # неизменяемый тег
git branch -f stable HEAD                                     # stable -> тот же bump
git push -f origin "refs/heads/stable:refs/heads/stable"      # rollout канала stable
