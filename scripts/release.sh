#!/bin/sh
# Релизный шаг авто-патча: bump-коммит -> main, неизменяемый тег vX.Y.Z, канал stable.
#
# ПОЧЕМУ ЭТО ФАЙЛ, А НЕ `run: |` В ci.yml. Релизный путь чинится ЗАМЕРОМ, а не
# рассуждением: инлайновый YAML-шаг нечем прогнать нигде, кроме самого CI, то есть
# нечем и проверить до раскатки на всех потребителей канала `stable`. Отдельный файл
# гоняется на стенде (bare-origin + клоны) и пинится юнит-тестом
# `tests/unit/test_release_script.py`, который запускает ИМЕННО ЭТОТ файл.
#
# ВХОД (env):
#   VERSION      — `vX.Y.Z`, последняя строка stdout у scripts/bump_version.py;
#   GITHUB_SHA   — коммит, НА КОТОРЫЙ сработал триггер (его же чекаутит
#                  actions/checkout@v4, поэтому он же — родитель bump-коммита).
# cwd — чекаут этого sha с уже сбампленными version-файлами.
set -eu

: "${VERSION:?VERSION (vX.Y.Z) is required}"
: "${GITHUB_SHA:?GITHUB_SHA is required}"

MAIN_BRANCH=main
STABLE_BRANCH=stable

# «Меня уже накрыли»: вершина main ОТЛИЧНА от моего sha и при этом СОДЕРЖИТ его —
# значит поверх меня уже приземлился более новый коммит, а мой bump лечь на main больше
# не может (он сидит поверх НЕ-вершины). Условие ОДНО на оба гейта, но «накрыли» с #740
# больше НЕ означает «всё в порядке»: накрыть может труп чужого job'а, поэтому зелёный
# выход требует отдельного доказательства — см. `skip_or_refuse` (tracker #716, #740).
# Дальше этого утверждение НЕ идёт, и намеренно: «релиз сделает ЕГО job, а мой коммит
# уедет в stable вместе с его bump'ом» — предсказание, а не знание, и ложным оно остаётся
# и после #740: в (3) у вершины прогон есть, но он ничего не выпустит, а осиротевший bump
# БЕЗ тега гейт пропускает честно. Ровно этот хвост круг 2 #716 убрал и отсюда, и из notice.
#
# Именно это условие, а не «тег занят»: занятое имя тега — лишь СИМПТОМ. Два job'а,
# чекаутящие РАЗНЫЕ sha с одинаковыми version-файлами, считают один и тот же следующий
# патч; переименовать версию мало — bump отставшего сидит поверх НЕ-вершины, поэтому
# `git push origin HEAD:main` у него всё равно non-fast-forward.
#
# Условие НАМЕРЕННО узкое — «не смог» и «не нужно» обязаны выглядеть по-разному, —
# но «всё остальное красное» из него НЕ следует, и обе оговорки ИЗМЕРЕНЫ, а не
# выведены. (1) main, откаченный force-push'ем НАЗАД, под условие не подходит (старая
# вершина — ПРЕДОК моего sha), поэтому job едет дальше и fast-forward'ом пушит bump
# поверх отката — ровно как делал этот шаг ДО гейта, байт-в-байт тот же исход на
# стенде с гейтом и без него. (2) отказ push'а по НЕ-гоночной причине разбирается
# ниже, у самой перепроверки, и там он честно назван проглатыванием.

# Спросить у origin, где сейчас ref $1. Отдаёт его ГЛОБАЛЬНО в $ref_head; код 1 =
# «спросить НЕ УДАЛОСЬ». Функция ОДНА на все три чтения рефа ПО ИМЕНИ — вершины main, канала
# stable и тега версии, — по тому же соображению, что и единственная строка решения ниже:
# мутация, снимающая любую из трёх точек отказа, обязана снимать защиту ЦЕЛИКОМ, а не
# половину. (Перечисление СПИСКА тегов сюда не входит: у него нет имени, чтобы спросить, —
# см. `read_tags`.)
#
# Рефспек ПОЛНЫЙ, и это не педантизм: `git fetch origin main` резолвит имя по всем
# пространствам имён, поэтому аннотированный ТЕГ с именем `main` уводит fetch на себя.
# Дальше ловушка захлопывается тихо: `rev-parse FETCH_HEAD` отдаёт объект тега (он НЕ
# равен sha коммита), а `merge-base --is-ancestor` его разыменовывает и честно отвечает
# «X предок X» — гейт получает «меня накрыли» на вершине, которая РОВНО мой коммит, и
# релиз молча не состоится. Измерено; поэтому же `^{commit}`.
#
# «Не смог спросить — не решай»: `set -e` внутри функции, чей код проверяет `if`, НЕ
# действует, поэтому каждый шаг обязан сказать «нет» САМ. Точек отказа три (`|| return 1`
# у fetch, `|| return 1` у rev-parse и то, что `merge-base --is-ancestor` с ПУСТЫМ
# аргументом отвечает «нет»), и КАКАЯ ИЗ НИХ ДЕРЖИТ — зависит от формы отказа. Измерено
# на git 2.50.1 (Apple Git-155), обе формы:
#   СЕТЕВЫЕ (нет remote, remote не репозиторий, объекты нечитаемы, рефа нет) — git
#   УСЕКАЕТ FETCH_HEAD в 0 байт, поэтому падает уже `rev-parse`, а первая строка тут
#   защита в глубину. Ровно поэтому мутация, снимающая её, ДОЛГО не убивала ни одного
#   теста: все стендовые отказы были сетевыми.
#   ЗАПИСЬ (FETCH_HEAD нельзя перезаписать): `error: cannot open '.git/FETCH_HEAD':
#   Permission denied`, rc=255, а файл остаётся ПРЕЖНИМ — `rev-parse` отдаёт код 0 и
#   УСТАРЕВШУЮ вершину. Здесь `|| return 1` у fetch — ЕДИНСТВЕННОЕ, что стоит между
#   протухшими данными и решением, и это НЕ теоретизирование: тест
#   test_a_stale_fetch_head_never_decides строит ровно это и краснеет от снятия строки
#   (control 0 failed -> 1 failed). Поэтому «упавший fetch усекает FETCH_HEAD» — НЕ
#   универсалия, и лишних точек тут нет ни одной.
# Второй тест, test_a_fetch_that_cannot_answer_is_never_a_skip, пинит наблюдаемое
# СВОЙСТВО поверх этого: не сумевший ответить fetch НИКОГДА не даёт skip. Со стороны
# канала то же свойство пинит test_an_unreadable_channel_is_never_green.
read_remote_ref() {
    git fetch --quiet origin "$1" || return 1
    ref_head=$(git rev-parse "FETCH_HEAD^{commit}") || return 1
}

read_tip() { read_remote_ref "refs/heads/${MAIN_BRANCH}" && tip="$ref_head"; }
read_channel() { read_remote_ref "refs/heads/${STABLE_BRANCH}" && channel="$ref_head"; }
# Третье чтение — тега, и оно нужно ровно в одном месте: в ЕДИНСТВЕННОЙ ветке, которая после
# отбитого push'а идёт в ЗЕЛЁНОЕ (#723). `^{commit}` тут ещё и разыменовывает аннотированный
# тег, поэтому сравнивать можно прямо с bump-коммитом.
read_tag() { read_remote_ref "refs/tags/${VERSION}" && tag_commit="$ref_head"; }
# Четвёртое чтение — СПИСКА тегов, и нужно оно ровно гейту честности skip'а ниже. По ИМЕНИ
# тут не спросишь: вопрос «вершину УЖЕ выпустили?» — про то, отмечена ли она хоть каким-то
# версионным тегом, а моё `$VERSION` — лишь одно из имён, которым она может быть отмечена
# (пока я стоял в очереди, поверх могло приземлиться и выпуститься несколько патчей).
# `ls-remote`, а не локальный `git tag --points-at`: actions/checkout@v4 тянет теги на момент
# ЧЕКАУТА, поэтому локальный список отвечает про прошлое — та же гоча, что у `read_tip`.
read_tags() { remote_tags=$(git ls-remote --tags origin) || return 1; }

# ЕДИНСТВЕННАЯ строка решения «меня накрыл СОСЕД» — одна на оба гейта, чтобы мутация
# в tests/unit/test_release_script.py снимала защиту целиком, а не половину.
superseded_by_neighbour() {
    [ "$tip" != "$GITHUB_SHA" ] && git merge-base --is-ancestor "$GITHUB_SHA" "$tip"
}

superseded() {
    read_tip || return 1
    superseded_by_neighbour
}

# Формулировка НАМЕРЕННО сужена до того, что скрипт ЗНАЕТ, и с #716-круга-2 сужена
# ЕЩЁ РАЗ. Прежний хвост «releasing it is that newer tip's job» назывался «тем, что мы
# знаем», а был предсказанием — и ложен он был в ТРЁХ из ЧЕТЫРЁХ проглатываний ниже: в
# (2) и в (4) вершина — bump-коммит, а на bump-коммитах прогонов НЕ БЫВАЕТ (по
# построению: GITHUB_TOKEN не ретриггерит CI, плюс ci-skip-маркер; перемерено на 60
# подряд bump-sha — у всех `gh run list --commit <полный sha>` отдаёт `[]`), а в (3)
# прогон у вершины есть, но он не выпускает релиз. #740 закрыла (2) и (4) в той форме, где
# вершина-bump НЕСЁТ свой тег, — но хвост от этого знанием не становится и возвращать его не
# надо: он остаётся ложен и в (3), и на осиротевшем bump'е БЕЗ тега, который гейт пропускает
# честно. Знаем мы ровно одно: вершина
# уже содержит нас, и мы ничего не запушили. Ровно это обе строки и говорят — ОДИНАКОВО.
skip() {
    echo "::notice::release skipped: main is at $1, which already contains $GITHUB_SHA; nothing pushed"
    echo "release skipped: main is at $1, which already contains $GITHUB_SHA; nothing pushed"
}

# ГЕЙТ ЧЕСТНОСТИ SKIP'а (tracker #740). «Меня накрыли» — ещё не «всё в порядке»: накрыть
# может ТРУП чужого job'а, и тогда зелёный skip покрывает релиз, которого не случилось ни у
# кого. Поэтому skip требует ПОЛОЖИТЕЛЬНОГО доказательства добросовестности, а не отсутствия
# подозрений, и доказательств РОВНО ДВА — оба читаются у REMOTE, оба взаимозаменяемы:
#   P1. КАНАЛ УЖЕ НЕСЁТ МОЙ sha. Релиз, увёзший меня, доехал до потребителей — спорить не о
#       чем, и не важно, чей он и в каком состоянии остальная доска.
#   P2. ВЕРШИНУ ЕЩЁ НИКТО НЕ ВЫПУСКАЛ — на ней нет ни одного версионного тега. Тогда мой skip
#       не свидетельствует ни о чём: `concurrency: release` сериализует релизные job'ы, но
#       очередь не обязана идти в порядке приземлений, и job вершины просто ещё не работал.
# Не сошлось ни одно — красное.
#
# «НЕ СМОГ СПРОСИТЬ — НЕ РЕШАЙ» ЗДЕСЬ ОТНОСИТСЯ РОВНО К ОДНОМУ ЧТЕНИЮ — списку тегов, — и
# писать «включая любое „спросить не удалось“» было бы ЛОЖЬЮ: доказательства ищутся ПО
# ОЧЕРЕДИ, поэтому нечитаемый (или отсутствующий) канал не решает ничего сам, он просто не
# даёт P1, и дальше всё решает P2. Отсутствующий `stable` — это ОБЫЧНОЕ состояние молодого
# репозитория, и зелёный skip на нём остаётся зелёным (так идёт, например,
# test_superseded_with_the_tag_still_free_also_skips). А вот сломанный список тегов гасит
# именно P2, и его пустой ответ НЕОТЛИЧИМ от честного «тегов нет», — поэтому фейл-клоуз стоит
# там (test_an_unanswerable_tag_read_is_never_a_skip).
#
# ПОЧЕМУ ПРИЗНАК ИМЕННО ТАКОЙ, а не «вершина выглядит как bump». Дешёвый разбор ТЕМЫ коммита
# (`^chore: v`) измерен на этом же стенде предыдущим кругом и ОТВЕРГНУТ: control 0 failed;
# кандидат 5 failed, из них ЧЕТЫРЕ — здоровые superseded-пути. В здоровом накрытии вершина
# СПЛОШЬ И РЯДОМ bump-коммит (сосед приземлился и нормально зарелизился), поэтому ФОРМА
# вершины не отличает «сосед выпустился» от «сосед умер, не дорелизившись». Отличает их не
# форма, а ФАКТ: тег на вершине говорит, что её релиз УЖЕ ДОШЁЛ до атомарного push'а, — и
# раз дошёл, а канал меня не несёт, то релиз собран не до конца.
#
# ЦЕНА ЭТОГО ВЫБОРА, названная сразу: признак — ТЕГ, поэтому осиротевший bump БЕЗ ТЕГА
# проходит P2 честно и глотается как раньше. Этот скрипт такой вершины не строит (под
# `atomic` bump без тега не остаётся), но снаружи она достижима двумя маршрутами — сервер,
# который `atomic` объявил и не соблюл, и человек, стирающий версионный тег, — так что
# остаток НАЗВАН и запинен (test_an_untagged_orphan_bump_still_swallows), а не забыт. Взять
# его нечем, кроме той самой ФОРМЫ вершины: тема коммита отвергнута замером выше, а версия в
# файлах вершины ложно краснела бы на РУЧНОМ minor/major-бампе — задокументированной
# процедуре этого репозитория, которая двигает версию, не будучи релизом.
#
# ЧЕМ ЭТО ДЕРЖИТСЯ, КРОМЕ САМОГО ФАКТА: тем, что `concurrency: release` в ci.yml не даёт двум
# релизным job'ам идти одновременно, поэтому к моменту моего чтения job вершины УЖЕ ЗАКОНЧИЛ,
# а не висит между своими двумя push'ями. Зависимость эта на ТОЧНОСТЬ, а не на безопасность:
# пропади группа — красный сможет сработать на состоянии, которое сосед достроит секундой
# позже, но стоить это будет ровно того же, чего стоит любой красный на этой ветке, то есть
# внимания и ничего больше. Группа пинится отдельно (test_ci_serialises_release_jobs).
#
# ЧТО ЭТА КРАСНАЯ ВЕТКА СТОИТ — названо прямо, потому что новый красный на релизном пути
# репозитория стоит дорого по умолчанию. Здесь — НЕ стоит, и это свойство места: ветка, на
# которую он встаёт, не пушит НИЧЕГО, поэтому при зелёном и при красном на remote не двигается
# НИ ОДИН реф (пин проверяет все три — вершину, теги, канал). Значит он не может ни пропустить
# версию, ни занять имя тега, ни заморозить канал
# — он тратит внимание человека, а не пайплайн. Сравни с ценой соседних карточек, и сравни
# ТОЧНО, потому что они разные: у #723 (чужой тег-сквоттер) встают ВЕРСИИ — каждый следующий
# job умирает на `git tag -a`; у #737 (канал уведён рукой вне main) версии продолжают
# резаться, встаёт КАНАЛ. Здесь не встаёт ни то, ни другое. Ложных срабатываний три, все три
# знать заранее: лишнее удалённое чтение (флакнул `ls-remote` — job красный там, где раньше
# был зелёный skip); канал, откаченный ЧЕЛОВЕКОМ руками назад, — он честно перестаёт
# содержать недавние приземления, и об этом будет сказано на каждом накрытом job'е, пока
# канал не догонит; и вершина, чей job ещё не дошёл до push'а канала, — но этого не бывает,
# пока цела `concurrency`-группа (см. ниже).
#
# ЧТО ДЕРЖИТ КАЖДАЯ ПОЛОВИНА — свип, выборка `tests/unit/test_release_script.py`, collected
# 35 во всех раундах, возмущался МИР (этот файл), перед каждым раундом чистился
# `__pycache__` и стоял `PYTHONDONTWRITEBYTECODE=1`, восстановление сверялось по sha256:
# control 0 failed; снять гейт ЦЕЛИКОМ (безусловный `skip` первой строкой тела) 4 failed;
# снять ОДНО P1 (`if false` на проверке канала) 1 failed — и это ЗДОРОВЫЙ путь
# (`test_superseded_with_the_tag_already_taken_skips`), то есть без P1 гейт краснел бы на
# нормально зарелизившемся соседе; снять ОДНО P2 (`if false` на проверке тега) 3 failed;
# ПРЕВРАТИТЬ зелёный выход P2 в `exit 1` (то есть потребовать канал ВСЕГДА) 5 failed, и это
# ровно обычные гонки — `test_superseded_with_the_tag_still_free_also_skips`,
# `test_lost_race_after_the_pre_push_check_still_skips`, оба `..._lost_race_..._version_name`
# и пин-остаток; снять маршрутизацию ПЕРЕПРОВЕРКИ в гейт (там снова голый `skip`) 1 failed, и
# это `test_without_the_landed_question_the_release_is_lost`, а НЕ
# `test_lost_race_after_the_pre_push_check_still_skips` (тот идёт этой веткой, но остаётся
# зелёным и потому маршрутизацию не держит); control повторно 0 failed. Обе половины несущие,
# и несут они РАЗНОЕ: P1 — зелень здорового накрытия, P2 — И красноту трупа, И зелень обычной
# гонки, где job вершины просто ещё не стартовал. Раунд D — самый важный из пяти для чтения
# этого гейта: он показывает, что P2 не «поблажка», а несущая ЗЕЛЁНАЯ ветка.
skip_or_refuse() {
    if read_channel && git merge-base --is-ancestor "$GITHUB_SHA" "$channel"; then
        skip "$tip"                                   # P1
        exit 0
    fi
    if ! read_tags; then
        # ТОЛЬКО про список тегов: канал выше мог читаться прекрасно и просто ответить «нет».
        echo "main is at ${tip}, which already contains ${GITHUB_SHA}, and ${STABLE_BRANCH}" \
             "does not carry ${GITHUB_SHA}; the tag list on origin could not be read, so" \
             "whether anyone has released that tip is UNKNOWN. Refusing to call this a skip." \
             "Nothing pushed" >&2
        exit 1
    fi
    # Только ВЕРСИОННЫЕ теги: `ls-remote` перечисляет все подряд, а посторонний тег, повешенный
    # человеком на вершину, релизом её не делает — стенд, например, заводит тег с именем `main`.
    # Аннотированный тег даёт ДВЕ строки, и совпадёт вторая (`…^{}`), где sha уже разыменован.
    if printf '%s\n' "$remote_tags" | grep -Eq "^${tip}[[:space:]]+refs/tags/v"; then
        echo "main is at ${tip}, which already contains ${GITHUB_SHA} and is ALREADY TAGGED," \
             "yet ${STABLE_BRANCH} does not contain ${GITHUB_SHA}: the release that superseded" \
             "me got as far as its tag and has not moved the channel. Nothing pushed. If the" \
             "channel is merely behind, the next green landing carries it past this; if" \
             "something is REFUSING the channel push, that repeats until a human fixes it." \
             "By hand: git push origin ${tip}:refs/heads/${STABLE_BRANCH}" >&2
        exit 1
    fi
    skip "$tip"                                       # P2
    exit 0
}

git add pyproject.toml src/vikunja_mcp/__init__.py uv.lock
