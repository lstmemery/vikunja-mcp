#   #740 его НЕ закрывает и не претендует: тега на вершине тут нет, значит P2 выполняется
#   ЧЕСТНО — вершину действительно ещё никто не выпускал, — а «выпустит ли» отсюда
#   по-прежнему не спросить. Ровно этот вход и есть зелёный
#   test_superseded_with_the_tag_still_free_also_skips.
#   (4) ЗАКРЫТО #740 В ФОРМЕ «BUMP С ТЕГОМ». ПРЕДТЕГОВОЙ гейт, и это было НЕ (2) и НЕ (3):
#   вершину держит ЧУЖОЙ
#   осиротевший bump, а глотается ДРУГОЕ, более раннее приземление — на своём ПЕРВОМ и
